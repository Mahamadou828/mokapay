// Package investigation holds the case-management domain: the case an
// analyst opens, and the alerts bundled under it. The package is named
// for the activity rather than the entity because `case` is a Go keyword
// and cannot name a package.
package investigation

import (
	"errors"
	"time"

	"github.com/google/uuid"
)

// ErrCaseNotFound covers an unknown id and a soft-deleted one alike.
var ErrCaseNotFound = errors.New("case not found")

// ErrInvalidStatus rejects a status value outside the lifecycle.
var ErrInvalidStatus = errors.New("invalid case status")

// ErrLinkTargetMissing is returned when a link names a case or an alert
// that does not exist — the junction's foreign keys say so.
var ErrLinkTargetMissing = errors.New("case or alert not found")

// Status values mirror the stored compliance_case_status enum.
// StatusClosedSAR records that a Suspicious Activity Report was filed
// with the regulator: a distinct regulatory outcome, not a synonym of
// "closed".
type Status string

const (
	StatusOpen           Status = "open"
	StatusInvestigating  Status = "investigating"
	StatusClosedSAR      Status = "closed_sar"
	StatusClosedNoAction Status = "closed_no_action"
)

// IsClosing reports whether the status ends the investigation.
func (s Status) IsClosing() bool {
	return s == StatusClosedSAR || s == StatusClosedNoAction
}

// Case is the read entity: an investigation bundling one or more alerts.
type Case struct {
	ID         uuid.UUID
	Reference  string // CASE-2026-000042, generated server-side
	Status     Status
	AssigneeID *uuid.UUID
	Summary    *string
	ClosedAt   *time.Time
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// NewCase is the create payload. The reference is deliberately absent —
// it is generated by the database, never supplied by a caller.
type NewCase struct {
	Summary *string
}

// UpdateCase is the partial-update payload: nil means "don't change".
type UpdateCase struct {
	ID         uuid.UUID
	Status     *Status
	AssigneeID *uuid.UUID
	Summary    *string
}

// Filter narrows case listings; nil fields mean "not filtering".
type Filter struct {
	Status *Status
}

// Link is one alert-to-case membership.
type Link struct {
	CaseID    uuid.UUID
	AlertID   uuid.UUID
	CreatedAt time.Time
}
