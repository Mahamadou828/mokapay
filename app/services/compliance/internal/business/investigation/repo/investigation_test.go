func TestListCasesFilterByStatus(t *testing.T) {
	ctx := context.Background()
	cases, _ := newTestStores(t)

	created, err := cases.Add(ctx, investigation.NewCase{})
	if err != nil {
		t.Fatalf("adding case: %v", err)
	}
	sar := investigation.StatusClosedSAR
	if _, err := cases.Update(ctx, investigation.UpdateCase{ID: created.ID, Status: &sar}); err != nil {
		t.Fatalf("closing case: %v", err)
	}

	list, err := cases.List(ctx, investigation.Filter{Status: &sar}, 100)
	if err != nil {
		t.Fatalf("listing cases: %v", err)
	}
	if len(list) == 0 {
		t.Fatal("no closed_sar cases returned")
	}
	for _, c := range list {
		if c.Status != investigation.StatusClosedSAR {
			t.Fatalf("filter leaked a %q case", c.Status)
		}
	}
}

// Linking is idempotent: the pair IS the primary key, so a repeated link
// returns the existing membership instead of failing.
func TestAddAlertToCaseIsIdempotent(t *testing.T) {
	ctx := context.Background()
	cases, alerts := newTestStores(t)

	c, err := cases.Add(ctx, investigation.NewCase{})
	if err != nil {
		t.Fatalf("adding case: %v", err)
	}
	a := openAlert(ctx, t, alerts)

	first, err := cases.AddAlert(ctx, c.ID.String(), a.ID.String())
	if err != nil {
		t.Fatalf("linking alert: %v", err)
	}
	if first.CaseID != c.ID || first.AlertID != a.ID {
		t.Fatalf("link = %+v, want case %s / alert %s", first, c.ID, a.ID)
	}

	second, err := cases.AddAlert(ctx, c.ID.String(), a.ID.String())
	if err != nil {
		t.Fatalf("relinking alert: %v", err)
	}
	if !second.CreatedAt.Equal(first.CreatedAt) {
		t.Fatalf("relink rewrote created_at: %v → %v", first.CreatedAt, second.CreatedAt)
	}
}

