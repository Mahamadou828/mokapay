// Integration tests: need a migrated compliance database. Skipped unless
// TEST_DB_PORT is set:
//
//	TEST_DB_PORT=5433 go test ./internal/business/...
func newTestStores(t *testing.T) (repo.Store, evalrepo.Store) {
	t.Helper()

	port := os.Getenv("TEST_DB_PORT")
	if port == "" {
		t.Skip("TEST_DB_PORT not set; integration test needs a migrated compliance DB")
	}

	db := coredb.New(coredb.PostgresConfig{
		Host:     getenv("TEST_DB_HOST", "localhost"),
		Port:     port,
		Username: getenv("TEST_DB_USER", "mokapay"),
		Password: getenv("TEST_DB_PASSWORD", "mokapay"),
		Database: getenv("TEST_DB_NAME", "compliance"),
	})
	if err := db.Open(); err != nil {
		t.Fatalf("opening database: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })

	return repo.New(db), evalrepo.New(db)
}

func getenv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// openAlert runs one triggered evaluation and returns the alert it opened.
func openAlert(ctx context.Context, t *testing.T, alerts evalrepo.Store) evaluation.Alert {
	t.Helper()

	accountID := uuid.New()
	if _, err := alerts.Add(ctx, evaluation.NewRuleEvaluation{
		TransferID:  uuid.New(),
		RuleCode:    evaluation.RuleDailyVolumeLimit,
		SubjectType: evaluation.SubjectSender,
		AccountID:   new(accountID),
		Triggered:   true,
		Severity:    new(evaluation.SeverityHigh),
		RiskPoints:  35,
		Inputs:      json.RawMessage(`{"rolling_24h_volume_usd":50000}`),
	}); err != nil {
		t.Fatalf("adding rule evaluation: %v", err)
	}

	list, err := alerts.ListAlerts(ctx, evaluation.AlertFilter{AccountID: new(accountID)}, 10)
	if err != nil || len(list) != 1 {
		t.Fatalf("listing alerts: %v (got %d)", err, len(list))
	}
	return list[0]
}

// The reference is generated by the database — never supplied by the
// caller, so two concurrent creates cannot claim the same one.
func TestAddCaseGeneratesAReference(t *testing.T) {
	ctx := context.Background()
	cases, _ := newTestStores(t)

	summary := "structuring pattern across four transfers"
	created, err := cases.Add(ctx, investigation.NewCase{Summary: new(summary)})
	if err != nil {
		t.Fatalf("adding case: %v", err)
	}

	if !strings.HasPrefix(created.Reference, "CASE-") {
		t.Fatalf("reference = %q, want a CASE- prefix", created.Reference)
	}
	if created.Status != investigation.StatusOpen {
		t.Fatalf("status = %q, want open", created.Status)
	}
	if created.ClosedAt != nil {
		t.Fatalf("a new case carries closed_at %v", created.ClosedAt)
	}
	if created.Summary == nil || *created.Summary != summary {
		t.Fatalf("summary = %v, want %q", created.Summary, summary)
	}

	second, err := cases.Add(ctx, investigation.NewCase{})
	if err != nil {
		t.Fatalf("adding second case: %v", err)
	}
	if second.Reference == created.Reference {
		t.Fatalf("two cases share the reference %q", created.Reference)
	}

	got, err := cases.Get(ctx, created.ID.String())
	if err != nil {
		t.Fatalf("getting case: %v", err)
	}
	if got.Reference != created.Reference {
		t.Fatalf("read back reference %q, want %q", got.Reference, created.Reference)
	}
}

