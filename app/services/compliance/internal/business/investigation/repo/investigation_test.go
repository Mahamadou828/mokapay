// Closing a case stamps closed_at once; re-opening clears it.
func TestUpdateCaseClosure(t *testing.T) {
	ctx := context.Background()
	cases, _ := newTestStores(t)

	created, err := cases.Add(ctx, investigation.NewCase{})
	if err != nil {
		t.Fatalf("adding case: %v", err)
	}

	investigating := investigation.StatusInvestigating
	moved, err := cases.Update(ctx, investigation.UpdateCase{ID: created.ID, Status: &investigating})
	if err != nil {
		t.Fatalf("updating case: %v", err)
	}
	if moved.Status != investigation.StatusInvestigating {
		t.Fatalf("status = %q, want investigating", moved.Status)
	}
	if moved.ClosedAt != nil {
		t.Fatalf("an open case carries closed_at %v", moved.ClosedAt)
	}

	sar := investigation.StatusClosedSAR
	closed, err := cases.Update(ctx, investigation.UpdateCase{ID: created.ID, Status: &sar})
	if err != nil {
		t.Fatalf("closing case: %v", err)
	}
	if closed.Status != investigation.StatusClosedSAR {
		t.Fatalf("status = %q, want closed_sar", closed.Status)
	}
	if closed.ClosedAt == nil {
		t.Fatal("a closed case carries no closed_at")
	}

	// A later edit that does not move the status keeps the original
	// closure timestamp.
	note := "SAR filed 2026-07-28"
	again, err := cases.Update(ctx, investigation.UpdateCase{ID: created.ID, Summary: new(note)})
	if err != nil {
		t.Fatalf("updating closed case: %v", err)
	}
	if again.ClosedAt == nil || !again.ClosedAt.Equal(*closed.ClosedAt) {
		t.Fatalf("closed_at moved: %v → %v", closed.ClosedAt, again.ClosedAt)
	}

	// Re-opening clears it: a case cannot be open and closed at once.
	open := investigation.StatusOpen
	reopened, err := cases.Update(ctx, investigation.UpdateCase{ID: created.ID, Status: &open})
	if err != nil {
		t.Fatalf("re-opening case: %v", err)
	}
	if reopened.ClosedAt != nil {
		t.Fatalf("a re-opened case still carries closed_at %v", reopened.ClosedAt)
	}
}

