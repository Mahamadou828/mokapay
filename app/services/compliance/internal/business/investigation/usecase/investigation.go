// Package usecase implements case management: opening an investigation,
// moving it through its lifecycle (including the SAR-filed closure), and
// bundling alerts under it.
package usecase

import (
	"context"
	"errors"

	"github.com/google/uuid"
	"mokapay.app/app/services/compliance/internal/business/investigation"
	"mokapay.app/app/services/compliance/internal/business/investigation/repo"
	coredb "mokapay.app/core/db"
	"mokapay.app/core/logger"
)

// defaultListLimit caps an unbounded case listing.
const defaultListLimit = 50

type UseCase struct {
	logger *logger.Logger
	repo   repo.Store
}

func New(l *logger.Logger, db *coredb.Postgres) UseCase {
	return UseCase{
		logger: l,
		repo:   repo.New(db),
	}
}

// CreateCase opens an investigation. The reference is generated by the
// database — two concurrent creates cannot claim the same one.
func (u UseCase) CreateCase(ctx context.Context, data investigation.NewCase) (investigation.Case, error) {
	created, err := u.repo.Add(ctx, data)
	if err != nil {
		u.logger.Error(ctx, "Investigation.CreateCase: failed", "err", err)
		return investigation.Case{}, err
	}
	return created, nil
}

func (u UseCase) GetCase(ctx context.Context, id uuid.UUID) (investigation.Case, error) {
	return u.repo.Get(ctx, id.String())
}

func (u UseCase) ListCases(ctx context.Context, f investigation.Filter, limit int32) ([]investigation.Case, error) {
	if limit <= 0 {
		limit = defaultListLimit
	}
	return u.repo.List(ctx, f, limit)
}

// UpdateCase applies the partial update. Moving to a closed_* status
// stamps closed_at in the procedure.
func (u UseCase) UpdateCase(ctx context.Context, data investigation.UpdateCase) (investigation.Case, error) {
	if data.Status != nil {
		switch *data.Status {
		case investigation.StatusOpen, investigation.StatusInvestigating,
			investigation.StatusClosedSAR, investigation.StatusClosedNoAction:
		default:
			return investigation.Case{}, investigation.ErrInvalidStatus
		}
	}

	updated, err := u.repo.Update(ctx, data)
	if err != nil {
		if !errors.Is(err, investigation.ErrCaseNotFound) {
			u.logger.Error(ctx, "Investigation.UpdateCase: failed", "case", data.ID, "err", err)
		}
		return investigation.Case{}, err
	}

	return updated, nil
}

// AddAlertToCase bundles an alert under a case. Idempotent: relinking the
// same alert succeeds unchanged.
func (u UseCase) AddAlertToCase(ctx context.Context, caseID, alertID uuid.UUID) error {
	if _, err := u.repo.AddAlert(ctx, caseID.String(), alertID.String()); err != nil {
		if !errors.Is(err, investigation.ErrLinkTargetMissing) {
			u.logger.Error(ctx, "Investigation.AddAlertToCase: failed",
				"case", caseID, "alert", alertID, "err", err)
		}
		return err
	}
	return nil
}
